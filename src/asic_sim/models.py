from __future__ import annotations

from dataclasses import dataclass


GB = 1e9


@dataclass(frozen=True, slots=True)
class ModelSpec:
    """Static metadata sufficient for M0/M1 architecture exploration.

    Parameter counts are authoritative inputs when published by the model vendor.
    The simulator deliberately does not instantiate or download model weights.
    """

    key: str
    name: str
    total_parameters: float
    active_parameters: float
    num_layers: int
    hidden_size: int
    num_experts: int = 0
    experts_per_token: int = 0
    shared_experts: int = 0
    dense_layers: int = 0
    moe_intermediate_size: int | None = None
    context_length: int | None = None
    architecture: str = "dense"
    source: str = ""
    notes: str = ""

    @property
    def moe_layers(self) -> int:
        return max(0, self.num_layers - self.dense_layers) if self.num_experts else 0

    def storage_bytes(self, bits_per_weight: float, overhead_fraction: float = 0.0) -> float:
        _validate_bits(bits_per_weight)
        _validate_overhead(overhead_fraction)
        return self.total_parameters * bits_per_weight / 8.0 * (1.0 + overhead_fraction)

    def active_weight_bytes(self, bits_per_weight: float, overhead_fraction: float = 0.0) -> float:
        _validate_bits(bits_per_weight)
        _validate_overhead(overhead_fraction)
        return self.active_parameters * bits_per_weight / 8.0 * (1.0 + overhead_fraction)

    def hidden_bytes(self, activation_bits: float = 16.0) -> float:
        _validate_bits(activation_bits)
        return self.hidden_size * activation_bits / 8.0

    def minimum_bits_for_capacity(self, capacity_bytes: float, overhead_fraction: float = 0.0) -> float:
        """Maximum average bits/weight that fit into the supplied capacity."""
        if capacity_bytes <= 0:
            raise ValueError("capacity_bytes must be positive")
        _validate_overhead(overhead_fraction)
        return capacity_bytes * 8.0 / (self.total_parameters * (1.0 + overhead_fraction))

    def approximate_moe_network_bytes(
        self,
        *,
        activation_bits: float = 16.0,
        send_and_return: bool = True,
        remote_expert_fraction: float = 1.0,
    ) -> float:
        """Approximate activation traffic generated by routed experts per token."""
        if not 0.0 <= remote_expert_fraction <= 1.0:
            raise ValueError("remote_expert_fraction must be in [0, 1]")
        if not self.num_experts or not self.experts_per_token:
            return 0.0
        multiplier = 2.0 if send_and_return else 1.0
        return (
            self.moe_layers
            * self.experts_per_token
            * self.hidden_bytes(activation_bits)
            * multiplier
            * remote_expert_fraction
        )


def _validate_bits(bits: float) -> None:
    if bits <= 0:
        raise ValueError("bit width must be positive")


def _validate_overhead(overhead: float) -> None:
    if overhead < 0:
        raise ValueError("overhead_fraction cannot be negative")


